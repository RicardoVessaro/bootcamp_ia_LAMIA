print(type(1))  # mostra <class 'int'> representando inteiros
print(type(1.1))    # mostra <class 'float'> representando numeros com casas 
                    # decimais
print(type('texto'))    # mostra <class 'str'> representado Strings (textos)
print(type(False))  # mostra <class 'bool'> 
print(type(True))   # mostra <class 'bool'> representando booleanos (verdadeiro 
                    # ou falso)
