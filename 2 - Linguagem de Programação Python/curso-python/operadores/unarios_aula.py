# Operadores unários operam em um operando.
# `not`: Operador de negação lógica feita em uma variável booleana.
print(not False)    # mostra: True
print(not True) # mostra: False

# `-`: Opera atribuindo o valor para negativo.
print(-3)   # mostra: -3
y = 4
print(-y)   # mostra: -4
# ao utilizar `--` ele altera o valor para positivo.
print(--3)  # mostra: 3
print(--y)  # mostra: 4
# Note que não é um operador de incremento ou decremento.

# `+`: Visto também como operador unário mas não influencia no valor.
print(+3)   # mostra: 3

# Em python não há um operador unário de incremento ou decremento.
